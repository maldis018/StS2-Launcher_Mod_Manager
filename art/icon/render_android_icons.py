"""Render the Android launcher icons from the SVG sources in this folder.

Usage (from the repo root):
    uv run --with cairosvg python art/icon/render_android_icons.py

Writes into android/res/, overriding the default Godot icons that ship in the
godot-lib AAR (same resource names, so the manifest and the splash theme in
res/values/themes.xml pick them up unchanged):

    mipmap-<dpi>/icon.png             legacy square icon (API < 26)
    mipmap-<dpi>/icon_round.png       legacy round icon (API < 26)
    mipmap-<dpi>/icon_foreground.png  adaptive foreground: the "II" alone
    mipmap-<dpi>/icon_background.png  adaptive background: midnight gradient
    mipmap-<dpi>/icon_monochrome.png  themed-icon silhouette (Android 13+)
    mipmap-anydpi-v26/icon.xml, icon_round.xml, themed_icon.xml

Sources:
    sts2-launcher-redux-icon.svg  the transparent "II" on a 512x512 canvas
    bg-midnight.svg               the full icon (rounded square, "II" at 75%)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import cairosvg

HERE = Path(__file__).resolve().parent
RES = HERE.parent.parent / "android" / "res"

# Legacy launcher icons are 48dp; adaptive layers are 108dp.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

BG_GRADIENT = (
    '<radialGradient id="bg" cx="0.5" cy="0.42" r="0.7">'
    '<stop offset="0" stop-color="#1B2A44"/><stop offset="1" stop-color="#0A1222"/>'
    "</radialGradient>"
)

# Bounding box of the "II" artwork in the 512 source canvas, including the
# 14px outline stroke: x 121..391, y 41..471.
GLYPH_CX, GLYPH_CY = 256.0, 256.0
GLYPH_HALF_DIAG = ((391 - 121) ** 2 + (471 - 41) ** 2) ** 0.5 / 2

# Adaptive icons: launchers may mask to any shape, and only a 66dp circle of
# the 108dp layer is guaranteed visible. Fit the artwork's bounding box inside
# that circle.
SAFE_RADIUS = 512 * (33 / 108)
FG_SCALE = SAFE_RADIUS / GLYPH_HALF_DIAG

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/icon/render_android_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/icon_background"/>
    <foreground android:drawable="@mipmap/icon_foreground"/>
    <monochrome android:drawable="@mipmap/icon_monochrome"/>
</adaptive-icon>
"""


def glyph_inner() -> str:
    """The <defs> + <use> body of the transparent "II" source, without <svg>."""
    src = (HERE / "sts2-launcher-redux-icon.svg").read_text(encoding="utf-8")
    body = re.search(r"<svg[^>]*>(.*)</svg>", src, re.S)
    if not body:
        sys.exit("could not parse sts2-launcher-redux-icon.svg")
    return re.sub(r"<title>.*?</title>", "", body.group(1), flags=re.S)


def centered(scale: float, inner: str) -> str:
    tx = 256 - GLYPH_CX * scale
    ty = 256 - GLYPH_CY * scale
    return f'<g transform="translate({tx:.3f} {ty:.3f}) scale({scale:.5f})">{inner}</g>'


def svg(body: str, defs: str = "") -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'viewBox="0 0 512 512" width="512" height="512"><defs>{defs}</defs>{body}</svg>'
    )


def monochrome_inner() -> str:
    """Solid white silhouette of the two pillars (outline included)."""
    inner = glyph_inner()
    glyph = re.search(r'<path id="glyph" d="([^"]+)"', inner).group(1)
    pillar = (
        f'<path d="{glyph}" fill="#FFFFFF" stroke="#FFFFFF" stroke-width="14" '
        'stroke-linejoin="round"/>'
    )
    return (
        f'<g transform="translate(188 0)">{pillar}</g>'
        f'<g transform="translate(324 0)">{pillar}</g>'
    )


def render(svg_text: str, out: Path, px: int) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    cairosvg.svg2png(
        bytestring=svg_text.encode("utf-8"),
        write_to=str(out),
        output_width=px,
        output_height=px,
    )


def main() -> None:
    full = (HERE / "bg-midnight.svg").read_text(encoding="utf-8")
    inner = glyph_inner()

    foreground = svg(centered(FG_SCALE, inner))
    background = svg('<rect width="512" height="512" fill="url(#bg)"/>', BG_GRADIENT)
    monochrome = svg(centered(FG_SCALE, monochrome_inner()))
    # Legacy round icon: midnight disc with the "II" at 62%, a little smaller
    # than the 75% of the rounded-square icon so the serifs clear the circle.
    round_icon = svg(
        '<circle cx="256" cy="256" r="256" fill="url(#bg)"/>' + centered(0.62, inner),
        BG_GRADIENT,
    )

    for dpi, mult in DENSITIES.items():
        d = RES / f"mipmap-{dpi}"
        legacy = round(48 * mult)
        layer = round(108 * mult)
        render(full, d / "icon.png", legacy)
        render(round_icon, d / "icon_round.png", legacy)
        render(foreground, d / "icon_foreground.png", layer)
        render(background, d / "icon_background.png", layer)
        render(monochrome, d / "icon_monochrome.png", layer)

    # The godot-lib AAR also ships density-less res/mipmap/ copies. Override
    # them too (at xxxhdpi size, as the AAR does) so no Godot default can win
    # a resource lookup.
    d = RES / "mipmap"
    render(full, d / "icon.png", 192)
    render(round_icon, d / "icon_round.png", 192)
    render(foreground, d / "icon_foreground.png", 432)
    render(background, d / "icon_background.png", 432)
    render(monochrome, d / "icon_monochrome.png", 432)

    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    for name in ("icon.xml", "icon_round.xml", "themed_icon.xml"):
        (anydpi / name).write_text(ADAPTIVE_XML, encoding="utf-8")

    # Store-listing size, handy for the GitHub release page / README.
    render(full, HERE / "icon-512.png", 512)
    print(f"wrote icons to {RES}")


if __name__ == "__main__":
    main()
